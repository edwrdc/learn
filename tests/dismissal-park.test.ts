/**
 * PARKED DISMISSALS (owner, 2026-10-04): ESC-discard while the turn is
 * still working. Mid-turn the stored record holds no pending question or
 * problem (the turn's messages land at settle), so the dismiss route
 * cannot validate — it PARKS the intent (202) and the turn's settle path
 * applies it against the freshly persisted record, only if the dismissed
 * thing really is pending there.
 *
 * These pins hold both halves: the pure park registry + apply against
 * fixture records, and the route's park contract under an isolated
 * LH_DATA_DIR (the birth-stamp discipline — the seam is set before any
 * config-loading import, every app-module import dynamic).
 */

import assert from "node:assert/strict";
import fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { after, describe, it } from "node:test";
import { routeEvent } from "./support-route-event.ts";

// ── the seam, BEFORE any config-loading import ──────────────────────────────
const TMP_DATA = fs.mkdtempSync(path.join(os.tmpdir(), "lh-dismissal-park-"));
process.env.LH_DATA_DIR = TMP_DATA;

const { chatStore } = await import("../src/session/store.ts");
const { openChatRuntime } = await import("../src/session/durable.ts");
const { applyParkedDismissal, parkDismissal } = await import(
	"../src/session/dismissal-park.ts"
);
const { isTurnRunning } = await import("../src/session/turn-liveness.ts");
const { subscribe } = await import("../src/platform/model/events.ts");
const {
	activeProblemOf,
	danglingQuestionOf,
	dismissedAnswer,
} = await Promise.all([import("../src/session/model/transcript.ts"), import("../src/session/model/questions.ts")]).then((ms) => Object.assign({}, ...ms));
const newMessageId = (await import("../src/session/model/transcript.ts")).newMessageId;
const { bareQuestionTools, posedPlaceholder } = await import("./support-tools.ts");
await import("./support-durable.ts");
const { handleChatInput } = await import("../src/session/turn.ts");
const { runningTurn } = await import("../src/session/turn-runs.ts");
const { createFauxCore, fauxAssistantMessage, fauxToolCall } = await import("@earendil-works/pi-ai");
process.env.OPENROUTER_API_KEY ??= "test-key-presence-gate";

const QUIZ = {
	question: "What is a cyclic group?",
	options: [{ label: "Generated by one element" }, { label: "Abelian" }],
	correctAnswer: "Generated by one element",
	explanation: "One generator.",
	type: "check",
	nodeId: "cyclic-groups",
};
const answeredCallIds = (messages: Array<{ role: string; toolCallId?: string }>) =>
	new Set(messages.filter((m) => m.role === "toolResult").map((m) => m.toolCallId));

after(() => {
	fs.rmSync(TMP_DATA, { recursive: true, force: true });
});

/** A record whose newest assistant message carries a DANGLING quiz call —
 *  the settled state a mid-turn dismissal parks against. */
async function chatWithDanglingQuiz(id: string): Promise<string> {
	const chat = await chatStore.createChat("park: dangling quiz");
	await chatStore.saveMessages(chat.id, [{
		id: newMessageId(),
		role: "assistant",
		content: [
			{ type: "text", text: "Quick check:" },
			{
				type: "toolCall",
				id: `${id}-q1`,
				name: "quiz",
				arguments: { question: "What is a cyclic group?" },
			},
		],
	} as never, posedPlaceholder(`${id}-q1`)]);
	return chat.id;
}

/** A record with an ACTIVE problem — the settled practice state a
 *  dismiss-problem park applies against. */
async function chatWithActiveProblem(): Promise<string> {
	const chat = await chatStore.createChat("park: active problem");
	const assistant = {
		id: newMessageId(),
		role: "assistant",
		content: [
			{
				type: "toolCall",
				id: "call-prob-1",
				name: "problem",
				arguments: { statement: "Prove |G|=p ⇒ cyclic", mode: "recall" },
			},
		],
	} as never;
	await chatStore.saveMessages(chat.id, [assistant]);
	return chat.id;
}

describe("the park registry", () => {

	it("apply with nothing parked is a no-op (no write, no emit)", async () => {
		const chat = await chatWithDanglingQuiz("noop");
		const before = (await chatStore.getChat(chat))!.messages.length;
		let emitted = 0;
		const off = subscribe((e) => {
			if (e.type === "record-changed" && e.chatId === chat) emitted++;
		});
		await applyParkedDismissal(chat);
		off();
		assert.equal(emitted, 0);
		assert.equal((await chatStore.getChat(chat))!.messages.length, before);
	});
});

describe("applyParkedDismissal — against real records", () => {
	it("applies a parked question dismissal to the dangling quiz call", async () => {
		const chat = await chatWithDanglingQuiz("apply-q");
		const pending = danglingQuestionOf((await chatStore.getChat(chat))!.messages);
		assert.ok(pending);
		parkDismissal(chat, {
			type: "dismiss",
			toolCallId: pending!.toolCallId,
			answer: dismissedAnswer("quiz", "What is a cyclic group?"),
		});
		let emitted = 0;
		const off = subscribe((e) => {
			if (e.type === "record-changed" && e.chatId === chat) emitted++;
		});
		await applyParkedDismissal(chat);
		off();
		assert.equal(emitted, 1);
		// The call is answered now — nothing dangles.
		assert.equal(danglingQuestionOf((await chatStore.getChat(chat))!.messages), null);
		assert.ok(answeredCallIds((await chatStore.getChat(chat))!.messages).has(pending!.toolCallId));
		assert.equal(await applyParkedDismissal(chat), false, "nothing stays parked");
	});

	it("applies a parked problem dismissal to the active problem", async () => {
		const chat = await chatWithActiveProblem();
		parkDismissal(chat, { type: "dismiss-problem", problemCallId: "call-prob-1" });
		await applyParkedDismissal(chat);
		// The marker freed the slot — no active problem remains.
		assert.equal(activeProblemOf((await chatStore.getChat(chat))!.messages), null);
	});

	it("keeps the park when the write fails, then applies it on retry", async () => {
		const chat = await chatWithDanglingQuiz("retry");
		const pending = danglingQuestionOf((await chatStore.getChat(chat))!.messages);
		assert.ok(pending);
		parkDismissal(chat, {
			type: "dismiss",
			toolCallId: pending!.toolCallId,
			answer: dismissedAnswer("quiz", "What is a cyclic group?"),
		});
		const runtime = await openChatRuntime(chat);
		const commit = runtime.harness.commit.bind(runtime.harness);
		let failed = false;
		runtime.harness.commit = (async (change: never, context: never) => {
			if (!failed) {
				failed = true;
				throw new Error("durable write failed");
			}
			return commit(change, context);
		}) as typeof runtime.harness.commit;
		try {
			await assert.rejects(() => applyParkedDismissal(chat), /durable write failed/, "the storage failure surfaces");
		} finally {
			runtime.harness.commit = commit as typeof runtime.harness.commit;
		}
		assert.equal(await applyParkedDismissal(chat), true, "the retained park applies on retry");
		assert.equal(danglingQuestionOf((await chatStore.getChat(chat))!.messages), null);
		assert.ok(answeredCallIds((await chatStore.getChat(chat))!.messages).has(pending!.toolCallId));
		assert.equal(await applyParkedDismissal(chat), false, "nothing stays parked");
	});

	it("drops a park that targets nothing (never materialized — silence)", async () => {
		const chat = await chatWithDanglingQuiz("drop");
		const before = (await chatStore.getChat(chat))!.messages.length;
		parkDismissal(chat, { type: "dismiss-problem", problemCallId: "call-ghost" });
		let emitted = 0;
		const off = subscribe((e) => {
			if (e.type === "record-changed" && e.chatId === chat) emitted++;
		});
		await applyParkedDismissal(chat);
		off();
		assert.equal(emitted, 0);
		assert.equal((await chatStore.getChat(chat))!.messages.length, before);
		assert.equal(await applyParkedDismissal(chat), false, "nothing stays parked");
	});
});

describe("the dismiss route — the park contract (202)", () => {
	it("parks (202) while a turn runs; the turn's settle lands the dismissal", async () => {
		const chat = await chatStore.createChat("park: live turn");
		await chatStore.saveSettings(chat.id, { model: { provider: "openrouter", id: "z-ai/glm-5.3-flash" } });
		let release!: () => void;
		const gate = new Promise<void>((resolve) => (release = resolve));
		const faux = createFauxCore({});
		faux.setResponses([
			async () => {
				await gate;
				return fauxAssistantMessage([fauxToolCall("quiz", QUIZ, { id: "call-park" })], { stopReason: "toolUse" });
			},
		]);
		const ack = await handleChatInput(
			chat.id,
			{ type: "text", text: "quiz me" },
			{ engine: { model: faux.getModel(), streamFn: faux.streamSimple }, tools: bareQuestionTools() },
		);
		assert.equal(ack.status, 200);

		// Mid-turn the quiz is not in the record yet: the route parks.
		const dismissRoute = await import("../src/routes/api/chats/[id]/dismiss/+server.ts");
		const res = await dismissRoute.POST(
			routeEvent(
				new Request(`http://test/api/chats/${chat.id}/dismiss`, {
					method: "POST",
					headers: { "Content-Type": "application/json" },
					body: JSON.stringify({
						input: { type: "dismiss", toolCallId: "call-park", answer: dismissedAnswer("quiz", QUIZ.question) },
					}),
				}),
				{ id: chat.id },
			),
		);
		assert.equal(res.status, 202);
		assert.deepEqual(await res.json(), { ok: true, parked: true });

		const wire = new Response(runningTurn(chat.id)!.subscribe()).text();
		release();
		await wire;
		assert.equal(await isTurnRunning(chat.id), false);
		const messages = (await chatStore.getChat(chat.id))!.messages;
		assert.equal(danglingQuestionOf(messages), null, "the settle applied the parked dismissal");
		const results = messages.filter((m: { role: string; toolCallId?: string }) => m.role === "toolResult" && m.toolCallId === "call-park");
		assert.equal(results.length, 1);
		assert.equal((results[0] as { details?: { dismissed?: boolean } }).details?.dismissed, true);
		assert.equal(await applyParkedDismissal(chat.id), false, "nothing stays parked");
	});

	it("still refuses honestly (400) with no turn and nothing dangling", async () => {
		const chat = await chatStore.createChat("park: nothing dangling").id;
		const dismissRoute = await import("../src/routes/api/chats/[id]/dismiss/+server.ts");
		const res = await dismissRoute.POST(
			routeEvent(
				new Request(`http://test/api/chats/${chat}/dismiss`, {
					method: "POST",
					headers: { "Content-Type": "application/json" },
					body: JSON.stringify({
						input: { type: "dismiss", toolCallId: "call-nowhere", answer: dismissedAnswer("quiz", "?") },
					}),
				}),
				{ id: chat },
			),
		);
		assert.equal(res.status, 400);
	});
});
